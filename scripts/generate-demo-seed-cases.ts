/**
 * Regenerates the server-side demo case allowlist from the browser seed.
 * Run after changing src/data-layer/seed: bun scripts/generate-demo-seed-cases.ts
 */
import { writeFileSync } from 'node:fs';
import { buildDemoSeedData } from '../src/data-layer/seed/demoAiCases';

const data = buildDemoSeedData();
const out = `// GENERATED by scripts/generate-demo-seed-cases.ts from src/data-layer/seed. Do not edit.
import type { DemoSeedData } from './demo-seed-cases.ts';

export const DEMO_SEED_DATA: DemoSeedData = ${JSON.stringify(data)};
`;
writeFileSync(new URL('../supabase/functions/_shared/demo-seed-cases.data.ts', import.meta.url), out);
console.log(`Wrote ${data.cases.length} cases and ${data.txs.length} transactions.`);
