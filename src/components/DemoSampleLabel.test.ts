import { describe, expect, it } from 'vitest';
import {
  DEMO_FALLBACK_LABEL, DEMO_LIVE_AI_LABEL, DEMO_LIVE_AI_NOTICE, DEMO_SAMPLE_LABEL, demoStrAuditJustification,
} from './DemoSampleLabel';

describe('demo STR labels', () => {
  it('labels live AI output', () => {
    expect(DEMO_LIVE_AI_LABEL).toBe('AI drafting on synthetic data');
    expect(DEMO_LIVE_AI_NOTICE).toBe('Generated on synthetic data. Not for filing.');
  });

  it('labels pre-written and fallback output the same way', () => {
    expect(DEMO_SAMPLE_LABEL).toBe('Sample output (pre-written for demo)');
    expect(DEMO_FALLBACK_LABEL).toBe(DEMO_SAMPLE_LABEL);
  });

  it('writes the live AI audit entry', () => {
    expect(demoStrAuditJustification('live_ai')).toBe('STR draft generated by AI on synthetic data.');
    expect(demoStrAuditJustification('live_ai', 'Make it shorter')).toBe('STR draft generated by AI on synthetic data (refinement): "Make it shorter"');
  });

  it('never calls fallback output AI in the audit entry', () => {
    expect(demoStrAuditJustification('fallback')).toBe('STR draft shown: Sample output (pre-written for demo).');
    expect(demoStrAuditJustification('sample', 'x')).not.toMatch(/AI/);
  });
});
