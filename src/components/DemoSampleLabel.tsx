import { Info } from 'lucide-react';
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from '@/components/ui/tooltip';

/** Demo labels: one for live model output on synthetic cases, one for pre-written or fallback text. */
export const DEMO_LIVE_AI_LABEL = 'AI drafting on synthetic data';
export const DEMO_LIVE_AI_NOTICE = 'Generated on synthetic data. Not for filing.';
export const DEMO_SAMPLE_LABEL = 'Sample output (pre-written for demo)';
/** Fallback output carries the same visible label as pre-written output; only the tooltip explains why. */
export const DEMO_FALLBACK_LABEL = DEMO_SAMPLE_LABEL;

/** Demo audit wording for STR drafts. */
export const DEMO_AUDIT_LIVE_AI = 'STR draft generated by AI on synthetic data';
export const DEMO_AUDIT_SAMPLE = `STR draft shown: ${DEMO_SAMPLE_LABEL}`;
export const demoStrAuditJustification = (source: 'live_ai' | 'sample' | 'fallback', instruction?: string) => {
  const base = source === 'live_ai' ? DEMO_AUDIT_LIVE_AI : DEMO_AUDIT_SAMPLE;
  return instruction === undefined ? `${base}.` : `${base} (refinement): "${instruction.slice(0, 120)}"`;
};

export const DEMO_SAMPLE_TOOLTIP =
  "Pre-written text for this fictional case. In the live system, drafts are generated from the case's own data and reviewed by an analyst.";
export const DEMO_LIVE_AI_TOOLTIP =
  "Written just now by an AI model from this fictional case. In the live system, drafts are generated from the case's own data and reviewed by an analyst.";
export const DEMO_FALLBACK_TOOLTIP =
  "The demo AI was unavailable, timed out or reached its limit, so this is pre-written sample text. In the live system, drafts are generated from the case's own data and reviewed by an analyst.";
export const DEMO_AI_LIMIT_MESSAGE = 'Demo AI limit reached for this session. Book a walkthrough to see it live';
export const DEMO_AI_CAPACITY_MESSAGE = 'Live AI demo is at capacity today. Book a walkthrough to see it live';
export const demoAiLimitMessage = (limit: false | 'session' | 'capacity' | undefined) =>
  limit === 'capacity' ? DEMO_AI_CAPACITY_MESSAGE : limit === 'session' ? DEMO_AI_LIMIT_MESSAGE : null;

export function DemoSampleLabel({ className = '', source }: { className?: string; source?: 'live_ai' | 'sample' | 'fallback' }) {
  const live = source === 'live_ai';
  const label = live ? DEMO_LIVE_AI_LABEL : DEMO_SAMPLE_LABEL;
  const tip = live ? DEMO_LIVE_AI_TOOLTIP : source === 'fallback' ? DEMO_FALLBACK_TOOLTIP : DEMO_SAMPLE_TOOLTIP;
  return (
    <span className={`inline-flex flex-wrap items-center gap-x-2 gap-y-1 ${className}`}>
      <TooltipProvider delayDuration={150}>
        <Tooltip>
          <TooltipTrigger asChild>
            <span
              tabIndex={0}
              className="inline-flex items-center gap-1 rounded-full border border-border bg-muted px-2 py-0.5 text-[10px] font-medium text-muted-foreground cursor-help focus:outline-none focus-visible:ring-2 focus-visible:ring-ring"
            >
              <Info className="h-2.5 w-2.5" aria-hidden />
              {label}
            </span>
          </TooltipTrigger>
          <TooltipContent className="max-w-xs text-xs">{tip}</TooltipContent>
        </Tooltip>
      </TooltipProvider>
      {live && <span className="text-[10px] font-medium text-foreground">{DEMO_LIVE_AI_NOTICE}</span>}
    </span>
  );
}
