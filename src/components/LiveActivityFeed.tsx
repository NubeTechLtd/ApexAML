import { useEffect, useRef, useState } from 'react';
import { useZone, useZoneNavigate } from '@/hooks/useZone';
import { ArrowRight } from 'lucide-react';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { SEED_ALERTS, SEED_CUSTOMERS, SEED_TRANSACTIONS } from '@/data-layer/seed/dataset';

type Severity = 'red' | 'amber' | 'green' | 'blue';

interface FeedEntry {
  id: string;
  time: string;
  severity: Severity;
  message: string;
}

const dotClass: Record<Severity, string> = {
  red: 'bg-[hsl(var(--risk-critical))]',
  amber: 'bg-[hsl(var(--risk-medium))]',
  green: 'bg-[hsl(var(--risk-low))]',
  blue: 'bg-blue-500',
};

const hhmm = (iso: string) => new Date(iso).toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit', timeZone: 'Africa/Lagos' });
const SEVERITY: Record<string, Severity> = { Critical: 'red', High: 'red', Medium: 'amber', Low: 'green' };

/** Opening feed: the most recent sample alerts, so names and amounts match the inbox. */
const INITIAL_ENTRIES: FeedEntry[] = [...SEED_ALERTS]
  .sort((x, y) => y.timestamp.localeCompare(x.timestamp))
  .slice(0, 15)
  .map((a) => {
    const c = SEED_CUSTOMERS.find((x) => x.num === a.customerNum);
    const total = SEED_TRANSACTIONS.filter((t) => t.alertId === a.id).reduce((sum, t) => sum + t.amountNGN, 0);
    return { id: `seed-${a.id}`, time: hhmm(a.timestamp), severity: SEVERITY[a.riskLevel] ?? 'amber', message: `${a.riskLevel} alert — ${a.ruleTriggered} — ${c?.fullName ?? a.id} — ₦${total.toLocaleString('en-NG')}` };
  });

const NAMES = SEED_CUSTOMERS.map((c) => c.fullName);

const TEMPLATES = (isDemo: boolean): { severity: Severity; build: (name: string) => string }[] => [
  { severity: 'red', build: (n) => `Critical alert — POS Structuring — ${n} — ₦${(Math.floor(Math.random() * 90) + 10) * 100_000}`.replace(/000000$/, '00,000') },
  { severity: 'red', build: (n) => `High alert — USSD Layering — ${n} — ₦${(Math.floor(Math.random() * 50) + 5)},${Math.floor(Math.random() * 900) + 100},000` },
  { severity: 'amber', build: (n) => `STR draft updated — ${n} — ${isDemo ? 'sample narrative edited by analyst' : 'narrative regenerated by AI Co-Pilot'}` },
  { severity: 'amber', build: (n) => `Rule triggered — Dormant Activation — ${n} — account inactive ${Math.floor(Math.random() * 18) + 6} months` },
  { severity: 'green', build: (n) => `KYC verification approved — ${n} — BVN + NIN match` },
  { severity: 'green', build: () => `Sanctions screen clear — ${Math.floor(Math.random() * 20) + 3} new onboardings` },
  { severity: 'blue', build: () => `CTR draft prepared — ${Math.floor(Math.random() * 5) + 1} transactions above ₦5M threshold` },
  { severity: 'blue', build: () => `goAML XML exported — ${Math.floor(Math.random() * 6) + 1} STR drafts ready for analyst upload` },
];

function nowTime(): string {
  return new Date().toLocaleTimeString('en-GB', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
    timeZone: 'Africa/Lagos',
  });
}

export function LiveActivityFeed() {
  const navigate = useZoneNavigate();
  const isDemo = useZone() === 'demo';
  const [entries, setEntries] = useState<FeedEntry[]>(INITIAL_ENTRIES);
  const pausedRef = useRef(false);
  const counterRef = useRef(0);

  useEffect(() => {
    const interval = setInterval(() => {
      if (pausedRef.current) return;
      const templates = TEMPLATES(isDemo);
      const tpl = templates[Math.floor(Math.random() * templates.length)];
      const name = NAMES[Math.floor(Math.random() * NAMES.length)];
      counterRef.current += 1;
      const newEntry: FeedEntry = {
        id: `live-${Date.now()}-${counterRef.current}`,
        time: nowTime(),
        severity: tpl.severity,
        message: tpl.build(name),
      };
      setEntries((prev) => [newEntry, ...prev].slice(0, 30));
    }, 8000);
    return () => clearInterval(interval);
  }, []);

  return (
    <Card className="border-border bg-card shadow-sm flex flex-col">
      <CardHeader className="pb-2 flex flex-row items-center justify-between space-y-0">
        <div>
          <CardTitle className="text-sm font-semibold text-foreground">Live Activity Feed</CardTitle>
          <p className="text-[10px] text-muted-foreground">System-wide compliance events</p>
        </div>
        <div className="flex items-center gap-1.5">
          <span className="relative flex h-2 w-2">
            <span className="absolute inline-flex h-full w-full rounded-full bg-[hsl(var(--risk-low))] opacity-75 animate-ping" />
            <span className="relative inline-flex h-2 w-2 rounded-full bg-[hsl(var(--risk-low))]" />
          </span>
          <span className="text-[10px] font-semibold uppercase tracking-wide text-[hsl(var(--risk-low))]">Live</span>
        </div>
      </CardHeader>
      <CardContent className="pt-0 pb-3 flex-1 flex flex-col">
        <div
          className="flex-1 max-h-[420px] overflow-y-auto pr-1 -mr-1 divide-y divide-border/60"
          onMouseEnter={() => { pausedRef.current = true; }}
          onMouseLeave={() => { pausedRef.current = false; }}
        >
          {entries.map((e) => (
            <div key={e.id} className="flex items-start gap-2.5 py-2 text-[11px] animate-fade-in">
              <span className="text-muted-foreground tabular-nums shrink-0 mt-[2px]">{e.time}</span>
              <span className={`h-2 w-2 rounded-full shrink-0 mt-[5px] ${dotClass[e.severity]}`} />
              <span className="text-foreground leading-snug">{e.message}</span>
            </div>
          ))}
        </div>
        <button
          onClick={() => navigate('/system-audit')}
          className="mt-2 text-[11px] font-medium text-primary hover:underline inline-flex items-center gap-1 self-start"
        >
          View all activity <ArrowRight className="h-3 w-3" />
        </button>
      </CardContent>
    </Card>
  );
}

export default LiveActivityFeed;
